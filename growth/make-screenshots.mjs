#!/usr/bin/env node
// Renders the screenshot set every directory submission asks for.
//
// Directories want 3-5 shots of real UI. Benchmark charts are not UI, and a
// reviewer skimming twenty listings will not read a chart. These five are
// ordered the way a stranger meets the product: what it is, what it does to a
// sentence, what the tool actually prints, what it scores at, how it works.
//
//   01-hero          zero-slop.ai above the fold
//   02-rewrite       one before/after pair from the example gallery
//   03-terminal      real `slopscore.py --explain` output, not a mockup
//   04-benchmark     the current method-hidden incumbent chart, copied from assets/
//   05-engine        the eight-role diagram, rasterised from assets/engine.svg
//
// Shots 1 and 2 come from the live site so they cannot drift from what a
// reviewer sees when they click through. Shot 3 is generated by running the
// scorer, so the numbers on it are always real.
//
// Usage: node growth/make-screenshots.mjs [outdir]

import { chromium } from "../website/node_modules/playwright-core/index.mjs";
import { readFile, writeFile, copyFile, mkdir } from "node:fs/promises";
import { execFileSync } from "node:child_process";

const outDir = process.argv[2] ?? "assets/screenshots";
const site = process.env.SITE ?? "https://zero-slop.ai";
const chromePath =
  process.env.CHROME_PATH ??
  "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";

const W = 1440;
const H = 900;

await mkdir(outDir, { recursive: true });

// --- shot 3 input: run the real scorer -------------------------------------
// A fabricated terminal shot is the one thing a technical reviewer will catch,
// so the text on it is whatever the scorer prints today.
const SAMPLE = `In today's fast-paced digital landscape, businesses must leverage cutting-edge AI solutions to stay ahead of the curve. It's not just about adopting new technology, it's about fundamentally reimagining how we work. Our team is thrilled to announce a game-changing platform that empowers organizations to unlock their full potential.
`;
await writeFile("/tmp/zs-shot-sample.txt", SAMPLE);
const scorerOutput = execFileSync(
  "python3",
  ["scripts/slopscore.py", "--explain", "/tmp/zs-shot-sample.txt"],
  { encoding: "utf8" },
);

const esc = (s) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

// The scorer's severity bars and the score line carry the meaning; everything
// else is supporting detail and is dimmed so the shot reads at thumbnail size.
// Order matters and is not arbitrary. Every step below this one injects tags
// carrying quoted attributes, so the pass that underlines quoted spans has to
// run first — otherwise it matches class="heavy" inside markup this function
// just wrote and renders the attribute as visible text.
function colourise(raw) {
  return esc(raw)
    .replace(/(“[^”]*”|'[^'\n]*'|"[^"\n]*")/g, '<u>$1</u>')
    .replace(/█+/g, (m) => `<i class="heavy">${m}</i>`)
    .replace(/▓+/g, (m) => `<i class="mod">${m}</i>`)
    .replace(/[▒]+/g, (m) => `<i class="mild">${m}</i>`)
    .replace(/░+/g, (m) => `<i class="empty">${m}</i>`)
    .replace(/^(Writing score: )([\d.]+)(\/100)(\s+\[[^\]]+\])/m,
      '<b>$1</b><em class="score">$2</em><b>$3</b><span class="tag">$4</span>')
    .replace(/^(\s*)(WHERE TO EDIT[^\n]*)$/m, '$1<b class="rule">$2</b>');
}

const terminalHtml = `<!doctype html>
<html><head><meta charset="utf-8">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500;600&family=Manrope:wght@600&display=swap" rel="stylesheet">
<style>
  * { margin:0; padding:0; box-sizing:border-box; }
  body { width:${W}px; height:${H}px; background:#efe9dc; display:flex;
         align-items:center; justify-content:center; padding:44px;
         font-family:'Manrope',system-ui,sans-serif; }
  .win { width:100%; height:100%; background:#17150e; border-radius:12px;
         overflow:hidden; box-shadow:0 30px 70px -30px rgba(23,21,14,.6);
         display:flex; flex-direction:column; }
  .bar { height:38px; flex:none; display:flex; align-items:center; gap:8px;
         padding:0 15px; background:#211e15; border-bottom:1px solid #2e2a1e; }
  .bar i { width:11px; height:11px; border-radius:50%; display:block; }
  .bar .t { margin-left:12px; font-family:'IBM Plex Mono',monospace;
            font-size:12.5px; color:#8b8474; letter-spacing:.02em; }
  pre { flex:1; margin:0; padding:22px 26px; overflow:hidden;
        font-family:'IBM Plex Mono',monospace; font-size:11.5px; line-height:1.66;
        color:#b9b2a0; white-space:pre; }
  .cmd { color:#faf5e0; font-weight:500; }
  .cmd .p { color:#227B5B; }
  b { color:#faf5e0; font-weight:600; }
  u { color:#e8dfc6; text-decoration:none; }
  em.score { color:#d9705a; font-style:normal; font-weight:600; font-size:1.35em; }
  .tag { color:#d9705a; }
  b.rule { color:#c2b79a; letter-spacing:.06em; }
  i { font-style:normal; }
  i.heavy { color:#d9705a; }
  i.mod   { color:#c99a4e; }
  i.mild  { color:#8a8674; }
  i.empty { color:#3a362a; }
</style></head>
<body>
  <div class="win">
    <div class="bar"><i style="background:#e05f4d"></i><i style="background:#d7a44a"></i><i style="background:#3fa06a"></i>
      <span class="t">zero-slop &mdash; python3</span></div>
    <pre><span class="cmd"><span class="p">$</span> python3 scripts/slopscore.py --explain draft.txt</span>

${colourise(scorerOutput)}</pre>
  </div>
</body></html>`;

const browser = await chromium.launch({ executablePath: chromePath, headless: true });
const shots = [];

try {
  // --- 01 hero -------------------------------------------------------------
  const hero = await browser.newPage({ viewport: { width: W, height: H }, deviceScaleFactor: 2 });
  await hero.goto(site, { waitUntil: "networkidle" });
  await hero.evaluate(() => document.fonts.ready);
  // The hero animates a deck of sample cards; let one settle so the shot is not
  // caught mid-transition.
  await hero.waitForTimeout(2200);
  await hero.screenshot({ path: `${outDir}/01-hero.png` });
  shots.push("01-hero.png");
  await hero.close();

  // --- 02 rewrite pair -----------------------------------------------------
  const gallery = await browser.newPage({ viewport: { width: W, height: H }, deviceScaleFactor: 2 });
  await gallery.goto(site, { waitUntil: "networkidle" });
  await gallery.evaluate(() => document.fonts.ready);
  // #examples is the tabbed workbench holding the five before/after pairs.
  // Match it by id, not by text: a /before/i search finds the hero first,
  // because the hero deck cards carry the same vocabulary, and the shot then
  // duplicates 01 instead of showing anything new.
  const target = gallery.locator("#examples");
  await target.scrollIntoViewIfNeeded();
  // scrollIntoViewIfNeeded leaves focus on the skip-to-content link, which is
  // visible only while focused and otherwise reads as a stray black box in the
  // corner of the shot.
  await gallery.evaluate(() => document.activeElement?.blur());
  await gallery.waitForTimeout(1500);
  await target.screenshot({ path: `${outDir}/02-rewrite.png` });
  shots.push("02-rewrite.png");
  await gallery.close();

  // --- 03 terminal ---------------------------------------------------------
  const term = await browser.newPage({ viewport: { width: W, height: H }, deviceScaleFactor: 2 });
  await term.setContent(terminalHtml, { waitUntil: "load" });
  await term.evaluate(() => document.fonts.ready);
  await term.screenshot({ path: `${outDir}/03-terminal.png` });
  shots.push("03-terminal.png");
  await term.close();

  // --- 05 engine diagram ---------------------------------------------------
  const svg = await readFile("assets/engine.svg", "utf8");
  const diagram = await browser.newPage({ viewport: { width: 1600, height: 900 }, deviceScaleFactor: 2 });
  await diagram.setContent(
    `<!doctype html><html><head><meta charset="utf-8"><style>
      *{margin:0;padding:0}
      body{width:1600px;height:900px;background:#faf5e0;display:flex;
           align-items:center;justify-content:center;padding:56px}
      svg{width:100%;height:100%}
     </style></head><body>${svg}</body></html>`,
    { waitUntil: "load" },
  );
  await diagram.waitForTimeout(600);
  await diagram.screenshot({ path: `${outDir}/05-engine.png` });
  shots.push("05-engine.png");
  await diagram.close();
} finally {
  await browser.close();
}

// --- 04 benchmark ----------------------------------------------------------
await copyFile("assets/bench-incumbent-hidden.png", `${outDir}/04-benchmark.png`);
shots.push("04-benchmark.png");

console.log(`wrote ${shots.length} shots into ${outDir}/`);
for (const s of shots.sort()) console.log(`  ${s}`);
